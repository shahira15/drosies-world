def card(r):
    rid, g = r["id"], r["group"]
    archived = r["status"] == "archived"
    badge = ('<span class="badge badge-archived">Archived with DOI</span>' if archived
             else '<span class="badge badge-pub">Published web resource</span>')
    open_url = r["read_url"] if archived else r["file_url"]
    links = ['<a href="%s">%s</a>' % (esc(open_url), "Open the PDF" if rid.startswith("lesson-") else "Open the resource")]
    if archived:
        links.append('<a href="%s" rel="noopener">View the DOI record</a>' % esc(r["url"]))
    if r.get("parent"):
        links.append('<a href="/teacher-resources/#lessons">All seven lessons</a>')
    if archived:
        y, mo, d = r["date"].split("-")
        when = "Published %d %s %s%s" % (int(d), ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"][int(mo) - 1], y, " (Version %s)" % r["version"] if r.get("version") else "")
        meta = [("Date", esc(when))]
        if r.get("doi"):
            meta.append(("Version DOI", '<a href="%s" rel="noopener">https://doi.org/%s</a>' % (esc(r["url"]), esc(r["doi"]))))
        if r["id"] == "storybook":
            meta.append(("Concept DOI (all versions)", '<a href="https://doi.org/%s" rel="noopener">https://doi.org/%s</a>' % (CONCEPT_DOI, CONCEPT_DOI)))
            meta.append(("Licence", '<a href="%s" rel="noopener">%s</a> (as on the Zenodo record)' % (BOOK_LICENSE_URL, esc(BOOK_LICENSE))))
    else:
        meta = [("Date", "Not documented: cited as n.d. with your access date")]
    if r.get("ages"):
        meta.append(("Suggested ages", esc(r["ages"].replace("-undergraduate", " through undergraduate"))))
    dl = "".join("<div><dt>%s</dt><dd>%s</dd></div>" % (esc(k), v) for k, v in meta)
    tabs, panels = [], []
    for i, (key, label) in enumerate(FORMATS):
        text = getattr(F, key)(r)
        pid = "%s-%s" % (rid, key)
        tabs.append('<button type="button" role="tab" id="tab-%s" aria-controls="panel-%s" aria-selected="%s" tabindex="%s" data-fmt="%s">%s</button>'
                    % (pid, pid, "true" if i == 0 else "false", "0" if i == 0 else "-1", key, label))
        if key in ("bibtex", "ris"):
            body = '<pre class="cite-text cite-code" tabindex="0" aria-label="%s citation text"><code>%s</code></pre>' % (label, with_acc_spans(esc(text)))
            ext = "bib" if key == "bibtex" else "ris"
            extra = '<button type="button" class="dl-btn" data-download="%s" data-filename="%s.%s">Download .%s</button>' % (ext, esc(rid), ext, ext)
        else:
            body = '<p class="cite-text cite-rich">%s</p>' % with_acc_spans(em(text))
            extra = ""
        panels.append('<div role="tabpanel" id="panel-%s" aria-labelledby="tab-%s" data-fmt="%s"><h4 class="fmt-h">%s</h4>%s'
                      '<div class="cite-actions"><button type="button" class="copy-btn" data-copy aria-label="Copy %s citation for %s">Copy</button>%s</div></div>'
                      % (pid, pid, key, label, body, label, esc(r["short"]), extra))
    note = '<p class="card-note">%s</p>' % esc(r["note"]) if r.get("note") else ""
    return ('<article class="cite-card g-%s" id="%s" aria-labelledby="%s-h">'
            '<div class="card-top"><span class="card-ico" aria-hidden="true">%s</span>%s</div><h3 id="%s-h">%s</h3>'
            '<p class="card-desc">%s</p><p class="card-links">%s</p>%s<dl class="card-meta">%s</dl>'
            '<div class="cite-tabs" data-cite><div class="tablist" role="tablist" aria-label="Citation format for %s">%s</div>%s</div></article>'
            % (g, rid, rid, ICON[g], badge, rid, esc(r["short"]), esc(r["desc"]), " · ".join(links), note, dl, esc(r["short"]), "".join(tabs), "".join(panels)))


