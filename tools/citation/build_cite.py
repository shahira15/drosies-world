def jsonld(r):
    canon = r["file_url"]
    base = {"@context": "https://schema.org", "url": canon, "mainEntityOfPage": canon, "name": r["title"],
            "description": r["desc"], "inLanguage": "en", "isAccessibleForFree": True,
            "author": person(), "publisher": org(), "copyrightYear": int(YEAR),
            "isPartOf": {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": PUBLISHER},
            "citation": F.plain(F.apa(r))}
    base.update(age_props(r))
    if r["id"] == "storybook":
        base.pop("copyrightYear")
        base.update({"@type": ["Book", "LearningResource"], "datePublished": YEAR, "bookFormat": "https://schema.org/EBook",
                     "illustrator": {"@type": "Person", "name": "Letícia Cavalcanti"},
                     "identifier": {"@type": "PropertyValue", "propertyID": "DOI", "value": BOOK_DOI},
                     "sameAs": "https://doi.org/" + BOOK_DOI, "version": r["version"],
                     "learningResourceType": "Storybook"})
        return base
    if r["schema"] == "SoftwareApplication":
        base.update({"@type": "SoftwareApplication", "applicationCategory": "EducationalApplication",
                     "operatingSystem": "Any (web browser)",
                     "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"}})
        return base
    base["@type"] = "LearningResource"
    base["learningResourceType"] = {"conference": "Interactive simulation"}.get(r["id"], LRT.get(r["ris"], "Teacher resource"))
    if r["id"] == "conference":
        base["interactivityType"] = "active"
    return base


def meta_block(r, with_jsonld):
    canon = r["file_url"]
    lines = [START,
             '<meta name="author" content="%s">' % esc(AUTHOR_FULL),
             '<meta name="citation_title" content="%s">' % esc(r["title"]),
             '<meta name="citation_author" content="Arzoo, Shahira Helal">',
             '<meta name="citation_author_institution" content="%s">' % esc(AFFILIATION),
             '<meta name="citation_publication_date" content="%s">' % YEAR,
             '<meta name="citation_publisher" content="%s">' % esc(_pub(r)),
             '<meta name="citation_public_url" content="%s">' % canon]
    if r.get("doi"):
        lines.append('<meta name="citation_doi" content="%s">' % r["doi"])
    lines.append('<link rel="cite-as" href="%s">' % esc(r["url"]))
    if with_jsonld:
        lines.append('<script type="application/ld+json">%s</script>' % json.dumps(jsonld(r), ensure_ascii=False, separators=(",", ":")))
    lines.append(END)
    return "\n".join(lines) + "\n"


def _pub(r):
    return r.get("publisher") or PUBLISHER


# Pages that get JSON-LD from this script. Others (teacher hub, biology, life-cycle activities) already
# contain their own JSON-LD, so they only receive the <meta> tags.
META_ONLY = {"teacher-resources", "fruit-fly-biology", "life-cycle-activities"}
SKIP_PAGES = {"platform", "cite"}


def inject_head():
    changed = []
    for r in R:
        if r["id"] in SKIP_PAGES or r["id"].startswith("lesson-"):
            continue
        rel = r["file"]
        path = os.path.join(ROOT, rel)
        s = open(path, encoding="utf-8").read()
        if START not in s and r["id"] == "conference":
            # replace the page's original single JSON-LD block with the enriched one
            s, n = re.subn(r'<script type="application/ld\+json">.*?</script>\n?', "", s, count=1, flags=re.S)
            assert n == 1, "conference JSON-LD not found"
        block = meta_block(r, r["id"] not in META_ONLY)
        if START in s:
            s = re.sub(re.escape(START) + r".*?" + re.escape(END) + "\n?", lambda m: block, s, flags=re.S)
        else:
            assert s.count("</head>") == 1, rel
            s = s.replace("</head>", block + "</head>")
        open(path, "w", encoding="utf-8", newline="").write(s)
        changed.append(rel)
    return changed


