def person():
    p = {"@type": "Person", "@id": AUTHOR_ID, "name": AUTHOR_FULL, "url": AUTHOR_ID,
         "affiliation": {"@type": "CollegeOrUniversity", "name": AFFILIATION_ORG}}
    if ORCID:
        p["sameAs"] = ORCID
    return p


def org():
    return {"@type": "Organization", "name": PUBLISHER, "url": SITE + "/"}


def age_props(r):
    a = r.get("ages")
    if not a:
        return {}
    if "undergraduate" in a:
        return {"typicalAgeRange": a.split("-")[0] + "-", "educationalLevel": "Ages 5 through undergraduate"}
    return {"typicalAgeRange": a}


LRT = {"COMP": "Interactive simulation", "ELEC": "Teacher resource", "GEN": "Activity sheet", "BOOK": "Storybook"}


def jsonld(r):
    canon = r["file_url"]
    base = {"@context": "https://schema.org", "url": canon, "mainEntityOfPage": canon, "name": r["title"],
            "description": r["desc"], "inLanguage": "en", "isAccessibleForFree": True,
            "author": person(), "publisher": org(),
            "isPartOf": {"@type": "WebSite", "@id": SITE + "/#website", "url": SITE + "/", "name": PUBLISHER},
            "citation": F.plain(F.apa(r, acc=False))}
    base.update(age_props(r))
    if r["id"] == "storybook":
        base.update({"@type": ["Book", "LearningResource"], "datePublished": r["date"], "license": BOOK_LICENSE_URL, "bookFormat": "https://schema.org/EBook",
                     "illustrator": {"@type": "Person", "name": ILLUSTRATOR},
                     "identifier": [{"@type": "PropertyValue", "propertyID": "DOI", "name": "Version DOI", "value": BOOK_DOI},
                                    {"@type": "PropertyValue", "propertyID": "DOI", "name": "Concept DOI", "value": CONCEPT_DOI}],
                     "sameAs": "https://doi.org/" + BOOK_DOI, "version": r["version"], "learningResourceType": "Storybook"})
        return base
    if r["schema"] == "SoftwareApplication":
        base.update({"@type": "SoftwareApplication", "applicationCategory": "EducationalApplication",
                     "operatingSystem": "Any (web browser)", "offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"}})
        return base
    base["@type"] = "LearningResource"
    base["learningResourceType"] = {"conference": "Interactive simulation"}.get(r["id"], LRT.get(r["ris"], "Teacher resource"))
    if r["id"] == "conference":
        base["interactivityType"] = "active"
    return base


def _pub(r):
    return r.get("publisher") or PUBLISHER


def meta_block(r, with_jsonld):
    canon = r["file_url"]
    lines = [START,
             '<meta name="author" content="%s">' % esc(AUTHOR_FULL),
             '<meta name="citation_title" content="%s">' % esc(r["title"]),
             '<meta name="citation_author" content="%s">' % esc(r.get("creator") or "%s, %s" % (AUTHOR_FAMILY, AUTHOR_GIVEN)),
             '<meta name="citation_author_institution" content="%s">' % esc(AFFILIATION)]
    if ORCID:
        lines.append('<meta name="citation_author_orcid" content="%s">' % esc(ORCID))
    if r["year"]:  # only dated (verified) resources get a publication date
        lines.append('<meta name="citation_publication_date" content="%s">' % r["date"].replace("-", "/"))
    lines += ['<meta name="citation_publisher" content="%s">' % esc(_pub(r)),
              '<meta name="citation_public_url" content="%s">' % canon]
    if r.get("doi"):
        lines.append('<meta name="citation_doi" content="%s">' % r["doi"])
    lines.append('<link rel="cite-as" href="%s">' % esc(r["url"]))
    if with_jsonld:
        lines.append('<script type="application/ld+json">%s</script>' % json.dumps(jsonld(r), ensure_ascii=False, separators=(",", ":")))
    lines.append(END)
    return "\n".join(lines) + "\n"


META_ONLY = {"teacher-resources", "fruit-fly-biology", "life-cycle-activities"}
SKIP_PAGES = {"platform", "cite", "software-archive"}


def inject_head():
    changed = []
    for r in R:
        if r["id"] in SKIP_PAGES or r["id"].startswith("lesson-"):
            continue
        path = os.path.join(ROOT, r["file"])
        s = open(path, encoding="utf-8").read()
        block = meta_block(r, r["id"] not in META_ONLY)
        if START in s:
            s = re.sub(re.escape(START) + r".*?" + re.escape(END) + "\n?", lambda m: block, s, flags=re.S)
        else:
            if r["id"] == "conference":
                s, n = re.subn(r'<script type="application/ld\+json">.*?</script>\n?', "", s, count=1, flags=re.S)
                assert n == 1
            assert s.count("</head>") == 1, r["file"]
            s = s.replace("</head>", block + "</head>")
        open(path, "w", encoding="utf-8", newline="").write(s)
        changed.append(r["file"])
    return changed


