"""Build the Drosie's World citation hub from tools/citation/metadata.json + resources.py.

Generates:
  cite/index.html                         the /cite/ page
  cite/drosies-world-bibliography.{bib,ris,enw}   downloads for Zotero, Mendeley, EndNote, LaTeX
  CITATION.cff                            GitHub "Cite this repository"
  tools/citation/VERIFICATION_CHECKLIST.md   items that still need the author's manual verification
and injects scholarly <meta> tags and Schema.org JSON-LD between
<!-- cite-meta:start --> and <!-- cite-meta:end --> markers in each resource page.

SAFETY RULES (verified by tests/citation/validate.py)
  * metadata.json is the only place DOI / ORCID / licence / version / release date are entered.
  * The generator never invents those values. null means "not verified" and is omitted.
  * It refuses to overwrite a CITATION.cff that was not generated by it (e.g. one maintained by hand
    in the software-release work) or that holds a DOI, ORCID, version, release date or licence that
    metadata.json does not contain. Copy the verified values into metadata.json first, or use
    --force-cff to overwrite on purpose.

Usage:  python3 tools/citation/build_cite.py [--force-cff]
"""
