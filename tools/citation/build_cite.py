ICON = {"platform": "🌍", "storybook": "📖", "software": "💾", "simulation": "🎮", "teacher": "🍎", "lesson": "📝", "more": "🔭"}
ACC_RE = re.compile(r"\[\[ACC:(\w+)\]\]")
esc = html.escape


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def em(text):
    return re.sub(r"\*(.+?)\*", r"<em>\1</em>", esc(text, quote=False))


def with_acc_spans(escaped_html):
    """Replace access-date tokens by spans the page script fills with the reader's own access date."""
    return ACC_RE.sub(lambda m: '<span class="acc" data-style="%s">[access date]</span>' % m.group(1), escaped_html)


# ------------------------------------------------------------------ CITATION.cff guard
PROTECTED_TOP = ("doi", "version", "date-released", "license", "identifiers", "preferred-citation")


def guard_cff(force):
    path = os.path.join(ROOT, "CITATION.cff")
    if force or not os.path.exists(path):
        return
    text = open(path, encoding="utf-8").read()
    if F.GEN_MARK not in text:
        sys.exit("REFUSING to overwrite CITATION.cff: it was not generated by this script (hand-maintained, e.g. by the "
                 "software-release work).\n  Copy its verified values (version, DOI, release date, licence, ORCID) into "
                 "tools/citation/metadata.json, then re-run with --force-cff.")
    try:
        old = yaml.safe_load(text) or {}
    except yaml.YAMLError as e:
        sys.exit("REFUSING to overwrite CITATION.cff: it is not valid YAML (%s). Fix it or use --force-cff." % e)
    new = F.cff_data()
    problems = []
    for k in PROTECTED_TOP:
        if k in old and old[k] != new.get(k):
            problems.append("%s: file has %r, metadata.json would give %r" % (k, old[k], new.get(k)))
    for o, n in zip(old.get("authors", []), new["authors"]):
        for k in ("orcid", "family-names", "given-names"):
            if k in o and o[k] != n.get(k):
                problems.append("authors.%s: file has %r, metadata.json would give %r" % (k, o[k], n.get(k)))
    if problems:
        sys.exit("REFUSING to overwrite verified values in CITATION.cff:\n  - " + "\n  - ".join(problems)
                 + "\n  Put the verified values in tools/citation/metadata.json (or use --force-cff).")


