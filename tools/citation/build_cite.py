def card(r):
    rid = r["id"]
    archived = r["status"] == "archived"
    badge = ('<span class="badge badge-archived">Archived with DOI</span>' if archived
             else '<span class="badge badge-pub">Published web resource</span>')
    links = ['<a href="%s">%s</a>' % (esc(r["file_url"] if not archived else r["read_url"]), "Open the resource" if not rid.startswith("lesson-") else "Open the PDF")]
    if archived:
        links.append('<a href="%s" rel="noopener">View the Zenodo record</a>' % esc(r["url"]))
    if r.get("parent"):
        links.append('<a href="/teacher-resources/#lessons">All seven lessons</a>')
    meta = [("Year", esc(YEAR + (" (Version %s)" % r["version"] if archived else " (site copyright year; the exact release date is not recorded)")))]
    if archived:
        meta.append(("DOI", '<a href="%s" rel="noopener">https://doi.org/%s</a>' % (esc(r["url"]), BOOK_DOI)))
    if r.get("first_commit"):
        meta.append(("First committed to GitHub", esc(r["first_commit"] + " (repository history, not a publication date)")))
    if r.get("ages"):
        meta.append(("Suggested ages", esc(r["ages"].replace("-undergraduate", " through undergraduate"))))
    dl = "".join("<div><dt>%s</dt><dd>%s</dd></div>" % (esc(k), v) for k, v in meta)
    tabs, panels = [], []
    for i, (key, label) in enumerate(FORMATS):
        text = getattr(F, key)(r)
        pid = "%s-%s" % (rid, key)
        sel = "true" if i == 0 else "false"
        tabs.append('<button type="button" role="tab" id="tab-%s" aria-controls="panel-%s" aria-selected="%s" tabindex="%s" data-fmt="%s">%s</button>'
                    % (pid, pid, sel, "0" if i == 0 else "-1", key, label))
        if key in ("bibtex", "ris"):
            body = '<pre class="cite-text cite-code" tabindex="0" aria-label="%s citation text"><code>%s</code></pre>' % (label, esc(text))
            ext = "bib" if key == "bibtex" else "ris"
            extra = ('<button type="button" class="dl-btn" data-download="%s" data-filename="%s.%s">Download .%s</button>'
                     % (ext, esc(rid), ext, ext))
        else:
            body = '<p class="cite-text cite-rich">%s</p>' % em(text)
            extra = ""
        panels.append(
            '<div role="tabpanel" id="panel-%s" aria-labelledby="tab-%s" data-fmt="%s"%s>'
            '<h4 class="fmt-h">%s</h4>%s'
            '<div class="cite-actions"><button type="button" class="copy-btn" data-copy aria-label="Copy %s citation for %s">Copy</button>%s</div></div>'
            % (pid, pid, key, "" if i == 0 else "", label, body, label, esc(r["short"]), extra))
    note = '<p class="card-note">%s</p>' % esc(r["note"]) if r.get("note") else ""
    return ('<article class="cite-card" id="%s" aria-labelledby="%s-h">'
            '<div class="card-top">%s</div><h3 id="%s-h">%s</h3>'
            '<p class="card-desc">%s</p><p class="card-links">%s</p>%s<dl class="card-meta">%s</dl>'
            '<div class="cite-tabs" data-cite><div class="tablist" role="tablist" aria-label="Citation format for %s">%s</div>%s</div></article>'
            % (rid, rid, badge, rid, esc(r["short"]), esc(r["desc"]), " · ".join(links), note, dl, esc(r["short"]), "".join(tabs), "".join(panels)))


