def org():
    return {"@type": "Organization", "name": PUBLISHER, "url": SITE + "/"}


def age_props(r):
    a = r.get("ages")
    if not a:
        return {}
    if "undergraduate" in a:
        return {"typicalAgeRange": a.split("-")[0] + "-", "educationalLevel": "Ages 5 through undergraduate"}
    return {"typicalAgeRange": a}


