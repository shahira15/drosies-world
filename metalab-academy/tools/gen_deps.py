"""Generate DEPENDENCIES.md (dependency + licence inventory) from the actually installed packages."""
import importlib.metadata as md, subprocess, shutil
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
rows = ["# Dependency and licence inventory (generated by tools/gen_deps.py)", "",
        "Licences are read from each package's own metadata/DESCRIPTION. **MetaLab itself has no licence chosen yet** - that is a decision for the project owner (see LICENSE_DECISION.md). Check each licence yourself before redistributing.", "",
        "## Python (direct)", "| package | version | licence (from metadata) |", "|---|---|---|"]
def lic(m):
    meta = m.metadata
    v = meta.get("License-Expression") or meta.get("License") or ""
    if not v or len(v) > 80: v = "; ".join(c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")) or (v[:60] + "…" if v else "not stated in metadata")
    return v
for name in ["streamlit", "numpy", "scipy", "pandas", "plotly", "pytest"]:
    try: m = md.distribution(name); rows.append(f"| {name} | {m.version} | {lic(m)} |")
    except md.PackageNotFoundError: rows.append(f"| {name} | not installed | - |")
rows += ["", "## R (used only for validation; not required to run the app)", "| package | version | licence (DESCRIPTION) |", "|---|---|---|"]
if shutil.which("Rscript"):
    code = 'for (p in c("metafor","metadat","jsonlite")) { d <- packageDescription(p); cat(p, "|", d$Version, "|", d$License, "\\n") }; cat("R |", as.character(getRversion()), "| GPL-2 | GPL-3 (see R documentation)\\n")'
    out = subprocess.run(["Rscript", "-e", code], capture_output=True, text=True).stdout.strip().splitlines()
    rows += [f"| {' | '.join(x.strip() for x in l.split('|', 2))} |" for l in out if "|" in l]
else: rows.append("| (R not installed here) | | |")
rows += ["", "## Other", "- Chromium/Playwright were used only for development screenshots (not a dependency).", "- No fonts, images, icons or datasets are bundled except small published example datasets (BCG) identified in `metalab/datasets.py` with their source.",
         "- Reference metadata comes from PubMed/Crossref records (bibliographic facts); no copyrighted article text is bundled.", "- Risk-of-bias tool domain NAMES only; official tool texts/guidance are not reproduced."]
(ROOT / "DEPENDENCIES.md").write_text("\n".join(rows) + "\n")
